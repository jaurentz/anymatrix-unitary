function S=um_resonant_scattering_spectral(n,E,H,W,Gamma)
%UM_RESONANT_SCATTERING_SPECTRAL Exact finite traces in decoupled models.
%   Exact sample phases are available when H and Gamma=W*W' are
%   diagonal in the SAME basis; coupling rows are orthogonal and the
%   on-shell S has eigenvalues (E-h_j-i*gamma_j)/(E-h_j+i*gamma_j),
%   plus n-m eigenvalues 1 for spectator open channels.
%   No general finite eigenphase law or CUE law follows from unitarity.
m=size(H,1);
blank=struct('kind','unknown','density',[],'support',[], ...
    'atoms',[],'moments',[]);
S=struct('family','resonant_scattering','dimension',n, ...
    'normalization','probability (density with respect to dtheta)', ...
    'finite',struct('kind','unknown','eigenvalues',[], ...
        'moments',[],'atoms',[]), ...
    'limit',blank,'ensemble',blank,'underlying',blank, ...
    'reference','Beenakker (1997); Brouwer, Frahm and Beenakker (1997)', ...
    'notes',['Finite trace eigenphase measure of S(E) at fixed real energy. ', ...
      'No generic exact spectrum or ensemble law for coupled channels; ', ...
      'complex resonance poles of H-iWW* and Wigner-Smith proper delay ', ...
      'times are NOT eigenphases of S(E).']);
tol=1e-12;
if norm(H-diag(diag(H)),'fro')>tol*max(1,norm(H,'fro')) ...
        || norm(Gamma-diag(diag(Gamma)),'fro') ...
                  >tol*max(1,norm(Gamma,'fro'))
    return
end
h=real(diag(H));
g=real(diag(Gamma));
z=(E-h-1i*g)./(E-h+1i*g);
if n>m,z=[z;ones(n-m,1)];end
S.finite.kind='exact';
S.finite.eigenvalues=@()z;
S.finite.atoms=struct('angles',angle(z),'weights',ones(n,1)/n);
S.finite.moments=@(k)trace_moments(z,k);
S.notes=['Exact finite trace eigenphases for diagonal Hermitian cavity ', ...
   'with pairwise orthogonal channel-coupling rows and any idle ', ...
   'orthogonal channels; obtained without eig(S). The density is ', ...
   'atomic, not a generic CUE ensemble law.'];
end

function v=trace_moments(z,k)
validateattributes(k,{'numeric'},{'real','integer','finite'});
v=reshape(mean(bsxfun(@power,z(:),reshape(k,1,[])),1),size(k));
end

function S=um_geometric_spectral(family,z,w,massvals,stiffvals)
%UM_GEOMETRIC_SPECTRAL Standard exact finite spectral trace descriptor.
%   Z is the one-sided set of n positive-frequency unit eigenvalues.
%   Real orthogonal-symplectic matrices have full spectrum [Z;conj(Z)].
if nargin<4,massvals=[];end
if nargin<5,stiffvals=[];end
z=z(:);w=w(:);n=numel(z);
blank=struct('kind','unknown','density',[],'support',[], ...
    'atoms',[],'moments',[]);
S=struct('family',family,'dimension',2*n, ...
    'normalization','probability (density with respect to dtheta)', ...
    'finite',struct('kind','exact','eigenvalues', ...
        @()[z;conj(z)],'moments',@(k)geom_moments(z,k),'atoms',[]), ...
    'limit',blank,'ensemble',blank,'underlying',blank, ...
    'reference','Hairer, Lubich and Wanner, Geometric Numerical Integration (2006)', ...
    'notes',['Exact finite conjugate-paired orthogonal-symplectic ', ...
        'eigenphases from a stable energy-preserving integration step; ', ...
        'no limiting density is asserted.'], ...
    'frequencies',w,'mass_eigenvalues',massvals, ...
    'stiffness_eigenvalues',stiffvals);
end

function m=geom_moments(z,k)
validateattributes(k,{'numeric'},{'real','integer','finite'});
values=[z(:);conj(z(:))];
m=reshape(mean(bsxfun(@power,values,reshape(k,1,[])),1),size(k));
end
